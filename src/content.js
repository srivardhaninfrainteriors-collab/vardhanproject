export function pageMeta(path) {
  const p = projects.find((p) => path === `projects/${p.slug}/`);
  if (p)
    return {
      title: `${p.title} | SRIVARDHAN Projects`,
      description: p.summary,
    };
  const s = services.find((s) => path === `services/${s.slug}/`);
  const i = inspiration.find((i) => path === `inspiration/${i.slug}/`);
  const j = journal.find((j) => path === `journal/${j.slug}/`);
  const c = campaigns[path.split("/")[1]];
  if (s)
    return {
      title: `${s.name} in Vijayawada | SRIVARDHAN`,
      description: s.intro,
    };
  if (i)
    return {
      title: `${i.title} — Design inspiration | SRIVARDHAN`,
      description: i.desc,
    };
  if (j)
    return {
      title: `${j.title} | The SRIVARDHAN Journal`,
      description: j.intro,
    };
  if (path.startsWith("consult/") && c)
    return { title: `${c.title} | SRIVARDHAN`, description: c.intro };
  const names = {
    "": "Interiors & Construction in Vijayawada",
    "services/": "Our Expertise",
    "projects/": "Projects & Design Inspiration",
    "studio/": "Our Philosophy",
    "journal/": "The Journal",
    "contact/": "Book a Private Consultation",
    "privacy/": "Privacy & Cookies",
    "terms/": "Website Terms",
    "admin/": "Lead Desk",
    "404/": "Page Not Found",
  };
  return {
    title: `${names[path] || "Page Not Found"} | SRIVARDHAN INFRA & INTERIORS`,
    description:
      "Thoughtful interiors, distinctive homes and construction in Vijayawada. Discover a considered approach to space with SRIVARDHAN INFRA & INTERIORS.",
  };
}
